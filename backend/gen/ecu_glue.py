# ------------------------- helpers ----------------------------------


def _emit_controller_start_block(num_channels: int) -> str:
    lines: list[str] = []
    for i in range(num_channels):
        lines.append(
            f"    (void)CanIf_SetControllerMode({i}u, CAN_CS_STARTED);"
        )
        lines.append(
            f"    (void)CanIf_SetPduMode({i}u, CANIF_ONLINE);"
        )
    return "\n".join(lines)


def _emit_ipdu_group_start_block(num_groups: int) -> str:
    lines: list[str] = []
    for i in range(num_groups):
        lines.append(f"    Com_IpduGroupStart({i}u, TRUE);")
    return "\n".join(lines)


# ----------------------------- entrypoint ---------------------------


def generate(
    project: Project,
    output_dir: Path,
    *,
    tick_period_ms: int = DEFAULT_TICK_PERIOD_MS,
) -> list[Path]:
    """Emit EcuM, Sched, App seam, and App_Demo into `output_dir`.

    Returns the written paths. A project without CanIf is treated as
    a host-only project and produces nothing — the same convention
    can_h7.generate() uses.
    """
    if project.canif is None:
        return []
    plan = _build_plan(project, tick_period_ms)

    reload_value = (SYSTICK_CLOCK_HZ // 1000) * plan.tick_period_ms

    ecum_c = _ECUM_C_TEMPLATE.format(
        num_channels=plan.num_channels,
        num_ipdu_groups=plan.num_ipdu_groups,
        controller_start_block=_emit_controller_start_block(plan.num_channels),
        ipdu_group_start_block=_emit_ipdu_group_start_block(plan.num_ipdu_groups),
    )

    sched_h = _SCHED_H.format(tick_period_ms=plan.tick_period_ms)
    sched_c = _SCHED_C_TEMPLATE.format(
        tick_period_ms=plan.tick_period_ms,
        systick_clock_mhz=SYSTICK_CLOCK_HZ // 1_000_000,
        reload=reload_value,
    )

    app_h = _APP_H.format(tick_period_ms=plan.tick_period_ms)

    if plan.tx_signal_name and plan.rx_signal_name:
        app_demo = _APP_DEMO_LOOPBACK_TEMPLATE.format(
            tx_signal_id=f"COM_SID_{plan.tx_signal_name}",
            rx_signal_id=f"COM_SID_{plan.rx_signal_name}",
            tx_interval_ms=100,
        )
    else:
        app_demo = _APP_DEMO_EMPTY

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    files = {
        "EcuM.h": _ECUM_H,
        "EcuM.c": ecum_c,
        "Sched.h": sched_h,
        "Sched.c": sched_c,
        "App.h": app_h,
        "App_Demo.c": app_demo,
    }
    written: list[Path] = []
    for name, body in files.items():
        p = output_dir / name
        p.write_text(body)
        written.append(p)
    return written
