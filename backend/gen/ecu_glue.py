_ECUM_C_TEMPLATE = """\
/*
 * EcuM.c — startup orchestration + `int main(void)` (PROMPT C3).
 *
 * GENERATED by backend/gen/ecu_glue.py. Do not edit by hand;
 * regenerate via `make generate` in hardware/stm32h753zi/.
 *
 * Subsumes the AUTOSAR EcuM/BswM split into one "BswM-lite" startup:
 * we have a single mode ("running"), so there's nothing to manage.
 * Init order is the same the manual src/main.c variant uses, which is
 * what the L2 host-sim node already proves end-to-end:
 *
 *   1. system_init_for_fdcan()      — PLL2Q → 80 MHz FDCAN clock
 *   2. board_init()                  — USART3 + (future) LEDs
 *   3. Can_Init → CanIf_Init → PduR_Init → Com_Init  (BSW chain)
 *   4. CanIf_SetControllerMode(STARTED) + SetPduMode(ONLINE)
 *   5. Com_IpduGroupStart for every group
 *   6. App_Init()                    — dev seam, before scheduler
 *   7. Sched_Init()                  — SysTick on, MainFunction pump
 *   8. WFI idle loop                  — all work runs in ISR context
 */

#include "stm32h753xx.h"

#include "Std_Types.h"
#include "Can.h"
#include "CanIf.h"
#include "PduR.h"
#include "Com.h"

#include "board.h"
#include "EcuM.h"
#include "Sched.h"
#include "App.h"

extern void system_init_for_fdcan(void);
extern Can_ConfigType Can_Config;

void EcuM_Init(void)
{{
    Can_Init(&Can_Config);
    CanIf_Init(NULL);
    PduR_Init(NULL);
    Com_Init(NULL);

    /* Bring every CAN controller up. {num_channels} channel(s). */
{controller_start_block}

    /* Start every Com I-PDU group. {num_ipdu_groups} group(s). */
{ipdu_group_start_block}
}}

int main(void)
{{
    system_init_for_fdcan();
    board_init();
    board_vcp_puts("openvinci-h7: boot (generated glue)\\r\\n");

    EcuM_Init();
    board_vcp_puts("openvinci-h7: BSW initialized\\r\\n");

    App_Init();
    Sched_Init();
    board_vcp_puts("openvinci-h7: scheduler running\\r\\n");

    /* Idle. All BSW + app work happens in SysTick_Handler. */
    for (;;) {{
        __WFI();
    }}
}}
"""


_SCHED_H = """\
/*
 * Sched.h — SysTick-driven cooperative scheduler (PROMPT C3).
 *
 * GENERATED by backend/gen/ecu_glue.py. Do not edit by hand;
 * regenerate via `make generate` in hardware/stm32h753zi/.
 */
#ifndef OPENVINCI_SCHED_H
#define OPENVINCI_SCHED_H

#ifdef __cplusplus
extern "C" {{
#endif

/* Tick period in milliseconds. Used by App_Demo.c when it computes
 * how many ticks to wait between Com_SendSignal calls. */
#define OPENVINCI_TICK_PERIOD_MS {tick_period_ms}u

/* Enables SysTick at the configured period. Must be called *after*
 * EcuM_Init — the BSW main-functions don't tolerate being entered
 * before their respective _Init runs. */
void Sched_Init(void);

#ifdef __cplusplus
}}
#endif

#endif /* OPENVINCI_SCHED_H */
"""


_SCHED_C_TEMPLATE = """\
/*
 * Sched.c — SysTick handler + MainFunction pump (PROMPT C3).
 *
 * GENERATED by backend/gen/ecu_glue.py. Do not edit by hand;
 * regenerate via `make generate` in hardware/stm32h753zi/.
 *
 * Tick: {tick_period_ms} ms @ {systick_clock_mhz} MHz HSI sysclk
 *       (= {reload} cycles per tick, SysTick LOAD = reload - 1)
 */

#include <stdint.h>

#include "stm32h753xx.h"

#include "Can.h"
#include "CanIf.h"
#include "Com.h"

#include "Sched.h"
#include "App.h"

void Sched_Init(void)
{{
    /* SysTick_Config is CMSIS's one-liner: writes LOAD, clears VAL,
     * sets CTRL = (CLKSOURCE | TICKINT | ENABLE) and the NVIC priority
     * to lowest. Returns non-zero on a reload value the 24-bit timer
     * can't hold — at 1 ms @ 64 MHz we're nowhere near that. */
    (void)SysTick_Config((uint32_t){reload}u);
}}

/* Strong override of the weak SysTick_Handler in
 * third_party/cmsis-device-h7's startup_stm32h753xx.s. */
void SysTick_Handler(void)
{{
    /* CAN driver: drain Tx confirmations + Rx FIFO 0. */
    Can_MainFunction_Write();
    Can_MainFunction_Read();

    /* CanIf: route confirmations/indications through its tables. */
    CanIf_MainFunction();

    /* Com: time signals out / handle Rx callbacks. */
    Com_MainFunctionRx();
    Com_MainFunctionTx();

    /* Application. Runs last so it sees fresh Rx data and its Tx
     * requests get picked up on the next Com_MainFunctionTx tick. */
    App_MainFunction();
}}
"""


