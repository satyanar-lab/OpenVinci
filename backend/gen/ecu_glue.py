"""STM32H7 integration-glue generator (PROMPT C3).

Emits the boilerplate every real project needs to actually boot and
run the OpenVinci BSW — so the dev's only responsibility is the
`App_Init() / App_MainFunction()` seam.

What this generator produces (into the same directory the vendor
generators and can_h7.py drop their *_Cfg.{c,h} into):

  EcuM.{c,h}  — startup orchestration. Calls the BSW init chain in
                the right order (Can_Init → CanIf_Init → PduR_Init →
                Com_Init), brings the CAN controller up
                (CanIf_SetControllerMode → CanIf_SetPduMode), starts
                every Com I-PDU group, hands control to App_Init, then
                fires up Sched and idles in WFI. Owns `int main(void)`.

  Sched.{c,h} — SysTick-driven cooperative scheduler. Pumps
                Can_MainFunction_{Write,Read}, CanIf_MainFunction,
                Com_MainFunction{Rx,Tx}, and the dev's
                App_MainFunction at the configured period (default
                1 ms). Defines SysTick_Handler so the cmsis-device-h7
                vector table picks it up.

  App.h       — declarations of `App_Init(void)` and
                `App_MainFunction(void)`. This is the seam the dev
                replaces with their real application.

  App_Demo.c  — sample App_*. For h7-loopback it ticks a counter and
                Com_SendSignal(COM_SID_TxSignal) every 100 ms, then
                Com_ReceiveSignal(COM_SID_RxSignal) and prints
                "RX=0xNN" on change. Marked `REPLACE ME` so it's
                obvious this file shouldn't survive into a real app.

The EcuM startup also subsumes what an AUTOSAR build would split into
EcuM (state manager) + BswM (BSW mode manager) — the "lite" version
the prompt asks for. We don't model modes; there's only "running."
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from engine import Project


# Tick period the SysTick-driven scheduler fires at. 1 ms matches what
# the manual src/main.c variant used; the BSW main-functions all
# tolerate being called this often. If a future project needs slower
# pumping, the generator takes `tick_period_ms` so it can be lifted
# into project.json.
DEFAULT_TICK_PERIOD_MS: int = 1

# Cortex-M7 SysTick reference clock. The generated EcuM has already
# called system_init_for_fdcan() (PLL2Q is up, FDCAN clock = 80 MHz),
# but sysclk itself is still HSI 64 MHz — that's what SysTick sees.
SYSTICK_CLOCK_HZ: int = 64_000_000


# -------------------------- project inspection ----------------------


@dataclass(frozen=True)
class _GluePlan:
    """What the generator decided based on the project. Kept separate
    from the template strings so the tests can assert on the plan
    directly."""

    tick_period_ms: int
    num_channels: int                  # number of CAN controllers (today: 1)
    num_ipdu_groups: int               # number of Com I-PDU groups (today: 1)
    tx_signal_name: str | None         # e.g. "TxSignal" for the demo
    rx_signal_name: str | None         # e.g. "RxSignal" for the demo


def _build_plan(project: Project, tick_period_ms: int) -> _GluePlan:
    # h7-loopback today has one CAN0 network, one I-PDU group, and a
    # TxSignal / RxSignal. We inspect Com to discover the signal
    # names the demo should drive — this is what makes App_Demo.c
    # specific to the project rather than a frozen copy.
    tx_name: str | None = None
    rx_name: str | None = None
    if project.com is not None:
        for net in project.com.networks:
            for msg in net.messages or []:
                for sig in msg.signals or []:
                    # `node` on a signal is "who receives it." If the
                    # network's `me` is in that list, this is an Rx
                    # signal for us; otherwise it's Tx.
                    receivers = sig.node if isinstance(sig.node, list) else [sig.node]
                    me = net.me
                    if me in receivers and rx_name is None:
                        rx_name = sig.name
                    elif me not in receivers and tx_name is None:
                        tx_name = sig.name

    num_channels = (
        len(project.canif.networks) if project.canif is not None else 1
    )
    num_ipdu_groups = (
        len(project.com.networks) if project.com is not None else 1
    )

    return _GluePlan(
        tick_period_ms=tick_period_ms,
        num_channels=num_channels,
        num_ipdu_groups=num_ipdu_groups,
        tx_signal_name=tx_name,
        rx_signal_name=rx_name,
    )


