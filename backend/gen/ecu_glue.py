_APP_DEMO_LOOPBACK_TEMPLATE = """\
/*
 * App_Demo.c — sample App_* implementation for h7-loopback.
 *
 * GENERATED by backend/gen/ecu_glue.py.
 *
 * ▸▸▸ REPLACE ME ◂◂◂
 *
 * This file exists so the firmware has a working `App_Init` /
 * `App_MainFunction` out of the box and the internal-loopback test
 * proves the path Com_Send → CanIf → FDCAN → CanIf → Com_Receive
 * works on real silicon. For a real app, drop in your own .c file
 * implementing the same two functions and drop this one from the
 * Makefile.
 *
 * Behaviour:
 *   - every {tx_interval_ms} ms, Com_SendSignal({tx_signal_id}, &tx_value);
 *     tx_value increments from 0x55.
 *   - on every tick, Com_ReceiveSignal({rx_signal_id}, &rx_value).
 *     If it differs from the previous value, prints "RX=0xNN" out
 *     the VCP via board_vcp_*.
 *
 * With FDCAN1 in INTERNAL LOOPBACK + h7-loopback's matched Tx/Rx
 * canid (0x100), each TxSignal echoes straight back as an RxSignal,
 * so the print fires roughly every {tx_interval_ms} ms.
 */

#include <stdint.h>

#include "Std_Types.h"
#include "Com.h"
#include "Com_Cfg.h"

#include "App.h"
#include "Sched.h"
#include "board.h"

#define TX_INTERVAL_MS {tx_interval_ms}u
#define TX_INTERVAL_TICKS (TX_INTERVAL_MS / OPENVINCI_TICK_PERIOD_MS)

static uint8_t  s_tx_value = 0x55u;
static uint8_t  s_rx_last  = 0x00u;
static uint32_t s_ticks_until_send = 0u;

void App_Init(void)
{{
    board_vcp_puts("openvinci-h7: app demo starting\\r\\n");
}}

void App_MainFunction(void)
{{
    if (s_ticks_until_send == 0u) {{
        (void)Com_SendSignal({tx_signal_id}, &s_tx_value);
        s_tx_value++;
        s_ticks_until_send = TX_INTERVAL_TICKS;
    }} else {{
        s_ticks_until_send--;
    }}

    uint8_t rx_value;
    if (E_OK == Com_ReceiveSignal({rx_signal_id}, &rx_value)) {{
        if (rx_value != s_rx_last) {{
            s_rx_last = rx_value;
            board_vcp_puts("openvinci-h7: RX=0x");
            board_vcp_put_hex8(rx_value);
            board_vcp_puts("\\r\\n");
        }}
    }}
}}
"""


